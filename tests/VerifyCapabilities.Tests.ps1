<#
    Unit-/Beispieltests für die reine, statische config.h-Pruefung von
    scripts/verify-capabilities.ps1.

    Es werden ZWEI Varianten gebaut: LGPL (OHNE GPL-Encoder libx264/libx265)
    und GPL (MIT libx264/libx265). BEIDE sind OHNE Hardware-Encoder: AMF und
    NVENC/NVDEC wurden entfernt (ARM64EC-Haenger auf Windows-on-ARM), die
    Pruefung VERBIETET sie daher in beiden Varianten. Die echte ffmpeg.exe
    existiert nur auf dem CI-Runner (und ist ARM64, also auf dem x64-Runner
    nicht ausfuehrbar); deshalb pruefen wir statisch aus FFmpegs config.h.
#>

BeforeAll {
    $script:RepoRoot = Split-Path -Parent $PSScriptRoot
    # Reine Logik per Dot-Sourcing laden, ohne den Skript-Rumpf auszuführen
    # (der Rumpf prüft $MyInvocation.InvocationName -ne '.').
    . (Join-Path $script:RepoRoot 'scripts/verify-capabilities.ps1')
}

Describe 'Get-FFmpegConfigFlags (config.h-Parser)' {
    It 'sammelt nur auf 1 gesetzte CONFIG_-Schalter (ohne Praefix, lowercase)' {
        $cfg = @'
/* Automatically generated by configure - do not modify! */
#define CONFIG_LIBX264_ENCODER 1
#define CONFIG_LIBX265_ENCODER 0
#define CONFIG_AAC_ENCODER 1
'@
        $flags = @(Get-FFmpegConfigFlags -ConfigText $cfg)
        $flags | Should -Contain 'libx264_encoder'
        $flags | Should -Not -Contain 'libx265_encoder'
        $flags | Should -Contain 'aac_encoder'
    }
    It 'liefert eine leere Menge fuer leeren Text' {
        @(Get-FFmpegConfigFlags -ConfigText '').Count | Should -Be 0
    }
}

Describe 'Test-FFmpegConfigCapabilities (statisch, LGPL ohne HW-Encoder)' {
    BeforeAll {
        # Reiner LGPL-Build: keine GPL-Encoder UND keine Hardware-Encoder.
        $script:CfgOk = @'
#define CONFIG_LIBX264_ENCODER 0
#define CONFIG_LIBX265_ENCODER 0
#define CONFIG_AAC_ENCODER 1
#define CONFIG_MP3_ENCODER 1
'@
    }

    It 'besteht fuer einen LGPL-Build ohne GPL- und ohne HW-Encoder' {
        $r = Test-FFmpegConfigCapabilities -ConfigText $script:CfgOk
        $r.Success | Should -BeTrue -Because $r.Message
        $r.Violations.Count | Should -Be 0
    }

    It 'schlaegt fehl bei vorhandenem libx264-Encoder' {
        $cfg = $script:CfgOk + "`n#define CONFIG_LIBX264_ENCODER 1"
        $r = Test-FFmpegConfigCapabilities -ConfigText $cfg
        $r.Success | Should -BeFalse
        ($r.Violations -join ' ') | Should -Match 'libx264'
    }

    It 'schlaegt fehl bei vorhandenem libx265-Encoder' {
        $cfg = $script:CfgOk + "`n#define CONFIG_LIBX265_ENCODER 1"
        $r = Test-FFmpegConfigCapabilities -ConfigText $cfg
        $r.Success | Should -BeFalse
        ($r.Violations -join ' ') | Should -Match 'libx265'
    }

    It 'schlaegt fehl bei (unerwartetem) AMF-Encoder' {
        $cfg = $script:CfgOk + "`n#define CONFIG_H264_AMF_ENCODER 1"
        $r = Test-FFmpegConfigCapabilities -ConfigText $cfg
        $r.Success | Should -BeFalse
        ($r.Violations -join ' ') | Should -Match 'AMF'
    }

    It 'schlaegt fehl bei (unerwartetem) NVENC-Encoder' {
        $cfg = $script:CfgOk + "`n#define CONFIG_H264_NVENC_ENCODER 1"
        $r = Test-FFmpegConfigCapabilities -ConfigText $cfg
        $r.Success | Should -BeFalse
        ($r.Violations -join ' ') | Should -Match 'NVENC'
    }

    It 'schlaegt fehl bei (unerwarteter) CUDA/NVDEC-Hardware-Beschleunigung' {
        $cfg = $script:CfgOk + "`n#define CONFIG_CUDA 1`n#define CONFIG_NVDEC 1"
        $r = Test-FFmpegConfigCapabilities -ConfigText $cfg
        $r.Success | Should -BeFalse
        ($r.Violations -join ' ') | Should -Match 'NVDEC/CUDA/ffnvcodec'
    }
}

Describe 'Test-FFmpegConfigCapabilities (statisch, GPL mit x264/x265, ohne HW-Encoder)' {
    BeforeAll {
        # GPL-Build: libx264 + libx265 ERFORDERLICH, KEINE Hardware-Encoder.
        $script:CfgGplOk = @'
#define CONFIG_LIBX264_ENCODER 1
#define CONFIG_LIBX265_ENCODER 1
#define CONFIG_AAC_ENCODER 1
#define CONFIG_MP3_ENCODER 1
'@
    }

    It 'besteht fuer einen GPL-Build mit x264/x265 und ohne HW-Encoder' {
        $r = Test-FFmpegConfigCapabilities -ConfigText $script:CfgGplOk -Variant gpl
        $r.Success | Should -BeTrue -Because $r.Message
        $r.Variant | Should -Be 'gpl'
        $r.Violations.Count | Should -Be 0
    }

    It 'schlaegt fehl, wenn libx264 im GPL-Build fehlt' {
        $cfg = $script:CfgGplOk -replace '#define CONFIG_LIBX264_ENCODER 1', '#define CONFIG_LIBX264_ENCODER 0'
        $r = Test-FFmpegConfigCapabilities -ConfigText $cfg -Variant gpl
        $r.Success | Should -BeFalse
        ($r.Violations -join ' ') | Should -Match 'libx264'
    }

    It 'schlaegt fehl, wenn libx265 im GPL-Build fehlt' {
        $cfg = $script:CfgGplOk -replace '#define CONFIG_LIBX265_ENCODER 1', '#define CONFIG_LIBX265_ENCODER 0'
        $r = Test-FFmpegConfigCapabilities -ConfigText $cfg -Variant gpl
        $r.Success | Should -BeFalse
        ($r.Violations -join ' ') | Should -Match 'libx265'
    }

    It 'schlaegt fehl, wenn im GPL-Build HW-Encoder (NVENC) auftauchen' {
        $cfg = $script:CfgGplOk + "`n#define CONFIG_H264_NVENC_ENCODER 1"
        $r = Test-FFmpegConfigCapabilities -ConfigText $cfg -Variant gpl
        $r.Success | Should -BeFalse
        ($r.Violations -join ' ') | Should -Match 'NVENC'
    }
}
